import mongoose, { Document, Schema } from 'mongoose';

export type NotificationType =
  | 'Vaccination'
  | 'Health'
  | 'Breeding'
  | 'Reminder'
  | 'Finance'
  | 'System'
  | 'warning'
  | 'info'
  | 'alert';

export interface INotification extends Document {
  userId: mongoose.Types.ObjectId;
  farmId: mongoose.Types.ObjectId;
  type: NotificationType;
  title: string;
  message: string;
  read: boolean;
  relatedEntity?: string;
  relatedEntityId?: string;
  autoGeneratedKey?: string;
  createdAt: Date;
}

const NotificationSchema = new Schema<INotification>(
  {
    userId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User ID is required for data isolation'],
      index: true,
    },
    farmId: {
      type: Schema.Types.ObjectId,
      ref: 'Farm',
      required: [true, 'Farm ID is required for data isolation'],
      index: true,
    },
    type: {
      type: String,
      default: 'System',
      trim: true,
    },
    title: {
      type: String,
      required: [true, 'Notification title is required'],
      trim: true,
    },
    message: {
      type: String,
      required: [true, 'Notification message is required'],
      trim: true,
    },
    read: {
      type: Boolean,
      default: false,
      index: true,
    },
    relatedEntity: {
      type: String,
      trim: true,
    },
    relatedEntityId: {
      type: String,
      trim: true,
    },
    autoGeneratedKey: {
      type: String,
      trim: true,
      index: true,
    },
    createdAt: {
      type: Date,
      default: Date.now,
      index: true,
    },
  }
);

NotificationSchema.index({ farmId: 1, read: 1, createdAt: -1 });
NotificationSchema.index({ farmId: 1, autoGeneratedKey: 1 });

export const Notification = mongoose.model<INotification>(
  'Notification',
  NotificationSchema
);
