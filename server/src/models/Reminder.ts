import mongoose, { Document, Schema } from 'mongoose';

export type ReminderStatus = 'Pending' | 'Completed' | 'Cancelled';
export type ReminderPriority = 'Low' | 'Medium' | 'High' | 'Urgent';

export interface IReminder extends Document {
  userId: mongoose.Types.ObjectId;
  farmId: mongoose.Types.ObjectId;
  type: string;
  title: string;
  description?: string;
  dueDate: Date;
  dueTime?: string;
  priority: ReminderPriority;
  status: ReminderStatus;
  relatedLivestockId?: mongoose.Types.ObjectId;
  notes?: string;
  autoGeneratedKey?: string;
  createdAt: Date;
  updatedAt: Date;
}

const ReminderSchema = new Schema<IReminder>(
  {
    userId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User ID is required for data isolation'],
      index: true,
    },
    farmId: {
      type: Schema.Types.ObjectId,
      ref: 'Farm',
      required: [true, 'Farm ID is required for data isolation'],
      index: true,
    },
    type: {
      type: String,
      required: [true, 'Reminder type is required'],
      trim: true,
      default: 'Other',
    },
    title: {
      type: String,
      required: [true, 'Reminder title is required'],
      trim: true,
    },
    description: {
      type: String,
      trim: true,
    },
    dueDate: {
      type: Date,
      required: [true, 'Due date is required'],
      index: true,
    },
    dueTime: {
      type: String,
      trim: true,
    },
    priority: {
      type: String,
      enum: ['Low', 'Medium', 'High', 'Urgent'],
      default: 'Medium',
    },
    status: {
      type: String,
      enum: ['Pending', 'Completed', 'Cancelled'],
      default: 'Pending',
      index: true,
    },
    relatedLivestockId: {
      type: Schema.Types.ObjectId,
      ref: 'Livestock',
    },
    notes: {
      type: String,
      trim: true,
    },
    autoGeneratedKey: {
      type: String,
      trim: true,
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

ReminderSchema.index({ farmId: 1, status: 1, dueDate: 1 });
ReminderSchema.index({ farmId: 1, autoGeneratedKey: 1 });

export const Reminder = mongoose.model<IReminder>('Reminder', ReminderSchema);
