import mongoose from 'mongoose';
import { Reminder } from '../models/Reminder';
import { Notification } from '../models/Notification';
import { Vaccination } from '../models/Vaccination';
import { BreedingRecord } from '../models/BreedingRecord';
import { HealthRecord } from '../models/HealthRecord';
import { Livestock } from '../models/Livestock';

export const syncAutomaticReminders = async (
  userId: string,
  farmId: string
): Promise<void> => {
  try {
    if (mongoose.connection.readyState !== 1) return;

    const farmObjId = new mongoose.Types.ObjectId(farmId);
    const userObjId = new mongoose.Types.ObjectId(userId);
    const now = new Date();

    // 1. Sync Vaccinations (upcoming nextDueDate within 30 days or overdue)
    const thirtyDaysAhead = new Date(now);
    thirtyDaysAhead.setDate(now.getDate() + 30);

    const vaccinations = await Vaccination.find({
      farmId: farmObjId,
      nextDueDate: { $lte: thirtyDaysAhead },
    })
      .populate('livestockId', 'animalId name')
      .lean();

    for (const v of vaccinations) {
      if (!v.nextDueDate) continue;
      const dateStr = new Date(v.nextDueDate).toISOString().split('T')[0];
      const autoKey = `auto-vaccine-${v._id}-${dateStr}`;

      const animalInfo = (v.livestockId as any)?.animalId
        ? ` (${(v.livestockId as any).animalId})`
        : '';

      const isOverdue = new Date(v.nextDueDate) < now;

      // Check if reminder already exists
      const exists = await Reminder.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Reminder.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Vaccination',
          title: `Vaccination: ${v.vaccine}${animalInfo}`,
          description: `Scheduled booster/vaccine dose for ${v.vaccine}.`,
          dueDate: v.nextDueDate,
          relatedLivestockId: (v.livestockId as any)?._id || v.livestockId,
          priority: isOverdue ? 'Urgent' : 'High',
          status: 'Pending',
          autoGeneratedKey: autoKey,
        });
      }
    }

    // 2. Sync Breeding (Calving / Delivery expected within 30 days)
    const breedingRecords = await BreedingRecord.find({
      farmId: farmObjId,
      pregnancyStatus: { $in: ['Confirmed Pregnant', 'Pregnant'] },
      expectedDeliveryDate: { $lte: thirtyDaysAhead },
    })
      .populate('livestockId', 'animalId name')
      .lean();

    for (const b of breedingRecords) {
      if (!b.expectedDeliveryDate) continue;
      const dateStr = new Date(b.expectedDeliveryDate).toISOString().split('T')[0];
      const autoKey = `auto-breeding-${b._id}-${dateStr}`;

      const animalInfo = (b.livestockId as any)?.animalId
        ? ` for ${(b.livestockId as any).animalId}`
        : '';

      const exists = await Reminder.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Reminder.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Breeding',
          title: `Expected Delivery / Calving${animalInfo}`,
          description: `Gestation period nearing completion. Prepare maternity pen and monitoring.`,
          dueDate: b.expectedDeliveryDate,
          relatedLivestockId: (b.livestockId as any)?._id || b.livestockId,
          priority: 'Urgent',
          status: 'Pending',
          autoGeneratedKey: autoKey,
        });
      }
    }

    // 3. Sync Health Follow-ups (within 30 days)
    const healthRecords = await HealthRecord.find({
      farmId: farmObjId,
      followUpDate: { $exists: true, $ne: null, $lte: thirtyDaysAhead },
    })
      .populate('livestockId', 'animalId name')
      .lean();

    for (const h of healthRecords) {
      if (!h.followUpDate) continue;
      const dateStr = new Date(h.followUpDate).toISOString().split('T')[0];
      const autoKey = `auto-health-${h._id}-${dateStr}`;

      const animalInfo = (h.livestockId as any)?.animalId
        ? ` (${(h.livestockId as any).animalId})`
        : '';

      const exists = await Reminder.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Reminder.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Health Check',
          title: `Health Follow-up: ${h.healthCondition || 'Medical Check'}${animalInfo}`,
          description: `Follow-up evaluation for symptoms: ${h.symptoms || 'General recovery check'}.`,
          dueDate: h.followUpDate,
          relatedLivestockId: (h.livestockId as any)?._id || h.livestockId,
          priority: 'Medium',
          status: 'Pending',
          autoGeneratedKey: autoKey,
        });
      }
    }
  } catch (error) {
    // Non-fatal background sync error
    console.error('Error in syncAutomaticReminders:', error);
  }
};

export const syncAutomaticNotifications = async (
  userId: string,
  farmId: string
): Promise<void> => {
  try {
    if (mongoose.connection.readyState !== 1) return;

    const farmObjId = new mongoose.Types.ObjectId(farmId);
    const userObjId = new mongoose.Types.ObjectId(userId);
    const now = new Date();

    const sevenDaysAhead = new Date(now);
    sevenDaysAhead.setDate(now.getDate() + 7);

    const fourteenDaysAhead = new Date(now);
    fourteenDaysAhead.setDate(now.getDate() + 14);

    // 1. Vaccination Notifications (Due Soon within 7 days OR Overdue)
    const vaccinations = await Vaccination.find({
      farmId: farmObjId,
      nextDueDate: { $lte: sevenDaysAhead },
    })
      .populate('livestockId', 'animalId name species')
      .lean();

    for (const v of vaccinations) {
      if (!v.nextDueDate) continue;
      const dateStr = new Date(v.nextDueDate).toISOString().split('T')[0];
      const isOverdue = new Date(v.nextDueDate) < now;
      const tag = isOverdue ? 'overdue' : 'due';
      const autoKey = `notif-vaccine-${tag}-${v._id}-${dateStr}`;

      const animalTag = (v.livestockId as any)?.animalId || 'Livestock';

      const exists = await Notification.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Notification.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Vaccination',
          title: isOverdue
            ? `Vaccination Overdue: ${v.vaccine}`
            : `Vaccination Due Soon: ${v.vaccine}`,
          message: isOverdue
            ? `Vaccine "${v.vaccine}" for animal ${animalTag} is overdue since ${dateStr}. Please administer immediately.`
            : `Vaccine "${v.vaccine}" for animal ${animalTag} is due on ${dateStr}.`,
          read: false,
          relatedEntity: 'Vaccination',
          relatedEntityId: v._id.toString(),
          autoGeneratedKey: autoKey,
        });
      }
    }

    // 2. Breeding Notifications (Calving within 14 days)
    const breedings = await BreedingRecord.find({
      farmId: farmObjId,
      pregnancyStatus: { $in: ['Confirmed Pregnant', 'Pregnant'] },
      expectedDeliveryDate: { $lte: fourteenDaysAhead },
    })
      .populate('livestockId', 'animalId name')
      .lean();

    for (const b of breedings) {
      if (!b.expectedDeliveryDate) continue;
      const dateStr = new Date(b.expectedDeliveryDate).toISOString().split('T')[0];
      const autoKey = `notif-breeding-${b._id}-${dateStr}`;
      const animalTag = (b.livestockId as any)?.animalId || 'Livestock';

      const exists = await Notification.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Notification.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Breeding',
          title: `Expected Delivery Approaching`,
          message: `Animal ${animalTag} has an expected calving/delivery date around ${dateStr}.`,
          read: false,
          relatedEntity: 'Breeding',
          relatedEntityId: b._id.toString(),
          autoGeneratedKey: autoKey,
        });
      }
    }

    // 3. Overdue Pending Reminders Notifications
    const overdueReminders = await Reminder.find({
      farmId: farmObjId,
      status: 'Pending',
      dueDate: { $lt: now },
    }).lean();

    for (const r of overdueReminders) {
      const dateStr = new Date(r.dueDate).toISOString().split('T')[0];
      const autoKey = `notif-reminder-overdue-${r._id}-${dateStr}`;

      const exists = await Notification.exists({ farmId: farmObjId, autoGeneratedKey: autoKey });
      if (!exists) {
        await Notification.create({
          userId: userObjId,
          farmId: farmObjId,
          type: 'Reminder',
          title: `Overdue Task: ${r.title}`,
          message: `Reminder "${r.title}" was scheduled for ${dateStr} and is currently overdue.`,
          read: false,
          relatedEntity: 'Reminder',
          relatedEntityId: r._id.toString(),
          autoGeneratedKey: autoKey,
        });
      }
    }
  } catch (error) {
    console.error('Error in syncAutomaticNotifications:', error);
  }
};
